"""Generate the standalone help page; no R execution or website-wide render."""
from html import escape
from pathlib import Path
from urllib.parse import quote
import argparse

ROOT = Path(__file__).resolve().parents[1]
TASKS = {
    'ingest': ('Ingest GWAS data', 'Help me ingest and validate new GWAS summary statistics using documented gact workflows.'),
    'annotations': ('Add biological annotations', 'Help me add or manage biological annotations in gact, checking provenance and available import interfaces.'),
    'analyze': ('Analyze genomic data', 'Help me plan a reproducible genomic analysis using gact data and annotations with the appropriate gsuite analysis packages, including biological interpretation.'),
    'extend': ('Extend gact', 'Help me prepare a gact bug, feature, database, workflow or documentation contribution.'),
    'report-a-bug-or-suggest-a-feature': ('Report a bug or suggest a feature', 'Help me prepare a bug report or feature request for gact or the relevant gsuite package, with a reviewable summary and the existing gtools submission guidance.'),
}


def render():
    prompt = (ROOT / 'assistant/instructions.txt').read_text(encoding='utf-8')
    cards = []
    for key, (title, task) in TASKS.items():
        url = 'https://chatgpt.com/?q=' + quote(prompt + '\nInitial task: ' + task, safe='')
        cards.append(f'''<section aria-labelledby="{key}"><h2 id="{key}">{title}</h2>
<p>{escape(task)}</p><p><a class="button" href="{escape(url, quote=True)}" target="_blank" rel="noopener noreferrer">Start in ChatGPT: {title}</a></p>
<button type="button" data-task="{escape(task, quote=True)}">Copy prompt: {title}</button></section>''')
    return '''<!doctype html>
<!-- Generated by assistant/build.py; edit assistant/instructions.txt or the generator. -->
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>gact AI assistant</title><style>
body{font:1.05rem/1.6 system-ui,sans-serif;max-width:58rem;margin:auto;padding:1.5rem;color:#203047;background:#fafcfe}
section{border:1px solid #ccd7e1;border-radius:.6rem;padding:1rem;margin:1rem 0;background:white}
a{color:#07558c}button,.button{font:inherit;display:inline-block;padding:.5rem .8rem;border:1px solid #07558c;border-radius:.3rem;background:white;color:#07558c;cursor:pointer}
pre{white-space:pre-wrap;overflow-wrap:anywhere}button:focus-visible,a:focus-visible{outline:3px solid #b45b00;outline-offset:3px}
</style><script src="assistant/launch.js" defer></script></head><body><main>
<p><a href="./">gact documentation</a></p><h1>gact AI assistant</h1>
<p>One assistant, four scientific and development tasks, plus bug reports and feature requests. Continue across tasks in the same conversation.</p>
<p>Use gact to acquire, organize and annotate genomic data, and the
<a href="https://psoerensen.github.io/gtools/gsuite/tutorials.html">gsuite ecosystem</a>
for statistical analyses. Check package availability and method-specific limitations.</p>
<p>Use synthetic examples and non-identifying summaries. Do not upload confidential or individual-level research data or credentials.</p>
<p>ChatGPT opens with shared instructions and your selected task ready. Review and press Send.
Conversations stay in your own AI account under your provider's policies; they are not automatically sent to gtools or gact maintainers.</p>
''' + '\n'.join(cards) + '''
<h2>Review and submit a request</h2>
<p>The assistant prepares a summary for your review. Follow the existing
<a href="https://psoerensen.github.io/gtools/support.html">gtools submission and tracking guidance</a>
for the current service availability, approved access and mailbox verification requirements.
You can also use that guidance to submit directly without AI. Drafting here does not
save or submit a request or launch development; maintainers choose which requests to address.</p>
<h2>Use another AI platform</h2>
<p>Use a Copy prompt button and paste into your own AI conversation. If sign-in interrupts the ChatGPT prefill, use the same route.</p>
<p id="copy-status" role="status" aria-live="polite"></p>
<p><a href="assistant/instructions.txt" download>Download complete portable instructions</a>. After pasting, describe your task.</p>
<details id="portable"><summary>View complete instructions and copy manually</summary>
<pre id="instructions">''' + escape(prompt) + '''</pre></details>
<p>Without JavaScript, use the ChatGPT links or download or manually copy the instructions above and describe your task.
This instructions-only assistant provides guidance, not access to private repositories or maintainer environments.
AI responses can be wrong: verify commands and scientific assumptions. Repository permissions enforce access.</p>
</main></body></html>
'''


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = ROOT / 'help.html'
    if args.check:
        if path.read_text(encoding='utf-8') != render():
            raise SystemExit('help.html is stale; run python assistant/build.py')
    else:
        path.write_text(render(), encoding='utf-8', newline='\n')
